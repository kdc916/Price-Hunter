const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const C=require('../cafe-compose.js');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const frontend=fs.readFileSync(path.join(__dirname,'..','cafe-ui.js'),'utf8');
const server=fs.readFileSync(path.join(__dirname,'..','worker/src/index.mjs'),'utf8');
const sw=fs.readFileSync(path.join(__dirname,'..','sw.js'),'utf8');
const cfg={name:'소니 ILCE-7M5 미개봉 바디',model:'ILCE-7M5',price:1500000,store:'마트',place:'야당점',condition:'new_sealed',mode:'official',userApproved:true,discoveredAt:'2026-10-19T13:05'};
const tests=[];const test=(name,fn)=>tests.push([name,fn]);
test('valid official report',()=>assert.deepEqual(C.validate(cfg),[]));
test('valid member report',()=>assert.deepEqual(C.validate({...cfg,mode:'member'}),[]));
test('reject no explicit consent',()=>assert.ok(C.validate({...cfg,userApproved:false}).length));
test('reject ambiguous buy price',()=>assert.ok(C.validate({...cfg,price:0}).length));
test('reject missing store',()=>assert.ok(C.validate({...cfg,store:''}).length));
test('reject missing location',()=>assert.ok(C.validate({...cfg,place:''}).length));
test('reject used condition',()=>assert.ok(C.validate({...cfg,condition:'used'}).length));
test('reject HTTP product link',()=>assert.ok(C.validate({...cfg,url:'http://example.com'}).length));
test('allow HTTPS purchase link',()=>assert.deepEqual(C.validate({...cfg,url:'https://example.com/item'}),[]));
test('title explicitly new product',()=>assert.ok(C.compose(cfg).title.includes('[신품 특가]')));
test('title includes exact price',()=>assert.ok(C.compose(cfg).title.includes('1,500,000원')));
test('post includes accurate store',()=>assert.ok(C.compose(cfg).body.includes('판매처: 마트')));
test('post includes discovery timestamp',()=>assert.ok(C.compose(cfg).body.includes('2026-10-19T13:05')));
test('post identifies condition',()=>assert.ok(C.compose(cfg).body.includes('새제품(미개봉)')));
test('post includes inventory caution',()=>assert.ok(C.compose(cfg).body.includes('재고: 확인 필요')));
test('post has no invented resale profit',()=>assert.doesNotMatch(C.compose(cfg).body,/예상 순이익:\s*\d/));
test('post has no invented online minimum',()=>assert.doesNotMatch(C.compose(cfg).body,/온라인 최저가:\s*\d/));
test('fingerprint stable for case and spaces',()=>assert.equal(C.fingerprint(cfg),C.fingerprint({...cfg,name:'  소니 ILCE-7M5 미개봉 바디 '})));
test('different price not duplicate fingerprint',()=>assert.notEqual(C.fingerprint(cfg),C.fingerprint({...cfg,price:1600000})));
test('both radio choices',()=>{assert.match(html,/name="cafeMode" value="official"/);assert.match(html,/name="cafeMode" value="member"/);});
test('cafe page accessible',()=>assert.match(html,/id="cafe"/));
test('cafe posting requires optin',()=>assert.match(html,/id="cafeApprove"/));
test('photo consent separate',()=>assert.match(html,/id="cafePhoto"/));
test('Naver login button',()=>assert.match(html,/id="cafeLogin"/));
test('explicit submit',()=>assert.match(frontend,/id\?==='cafePublish'|\$\('cafePublish'\)/));
test('do not auto post after scanning',()=>{const app=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');assert.match(app,/PriceHunterCafe\?\.prefill\(\)/);assert.doesNotMatch(app,/PriceHunterCafe\?\.publish\(/);});
test('admin review queue',()=>assert.match(html,/id="cafeQueue"/));
test('admin restricted on server',()=>assert.match(server,/if\(!user\.admin\)return problem/));
test('OAuth token encryption',()=>assert.match(server,/AES-GCM/));
test('OAuth anti-CSRF state',()=>assert.match(server,/ph_oauth/));
test('same-origin CSRF check',()=>assert.match(server,/verifyOrigin\(req\)/));
test('session cookie httpOnly',()=>assert.match(server,/HttpOnly; SameSite=Lax/));
test('single-use OAuth state',()=>assert.match(server,/DELETE FROM ph_oauth/));
test('member direct publish',()=>assert.match(server,/finishPublishing\(e,id,normalized,user,image\)/));
test('operator queue before publishing',()=>assert.match(server,/normalized\.mode==='official'\?'pending':'publishing'/));
test('operator atomic moderation',()=>assert.match(server,/WHERE id=\? AND status=\?/));
test('anti duplicate fingerprint',()=>assert.match(server,/fingerprint=\?/));
test('network failure not auto retried',()=>assert.match(server,/needs_review/));
test('rate limit',()=>assert.match(server,/\?\?\s*\d+|>=5/));
test('normal Naver Cafe article route',()=>assert.match(server,/\/menu\/\$\{board\}\/articles/));
test('file uses Naver supported image parameter',()=>assert.match(server,/f\.append\('image'/));
test('no secrets in static config',()=>assert.doesNotMatch(html+frontend,/NAVER_CLIENT_SECRET\s*=/));
test('v070 cache',()=>assert.match(sw,/price-hunter-v070/));
test('cache includes cafe frontend',()=>assert.match(sw,/cafe-ui\.js/));
let errors=0;for(const [name,fn] of tests){try{fn();console.log('PASS',name)}catch(err){console.log('FAIL',name,err.message);errors++;}}
console.log(`${tests.length-errors}/${tests.length} Cafe v0.7.0 tests`);if(errors)process.exitCode=1;
