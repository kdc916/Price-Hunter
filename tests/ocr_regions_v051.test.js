const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const R=require('../ocr-regions.js');
const S=require('../screenshot.js');
require('../catalogguard.js');require('../checkoutguard.js');require('../merchantguard.js');
const base=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(base,'app.js'),'utf8');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(base,'sw.js'),'utf8');
const tests=[];const t=(label,fn)=>tests.push([label,fn]);
const A=R.regions(675,250);
t('wide card 3 regions',()=>assert.equal(A.length,3));
t('wide card first area is price band',()=>assert.equal(A[0].name,'price-band'));
t('wide card price band intersects visible amount',()=>{const b=A[0];assert.ok(b.left<=229&&b.left+b.width>=425&&b.top<=158&&b.top+b.height>=171)});
t('wide card starts right of product image',()=>assert.ok(A[0].left>=100));
t('wide card coordinates safe',()=>{for(const x of A){assert.ok(x.left>=0&&x.top>=0&&x.width>0&&x.height>0&&x.left+x.width<=675&&x.top+x.height<=250)}});
t('portrait has lower price panel',()=>assert.equal(R.regions(720,1280)[0].name,'mobile-lower'));
t('desktop uses right-hand column',()=>assert.equal(R.regions(1400,1000)[0].name,'price-column'));
t('zero dims skip',()=>assert.equal(R.regions(0,500).length,0));
t('tiny image returns valid region',()=>assert.ok(R.regions(5,5).every(x=>x.width>0&&x.height>0)));
t('crop scales while preserving region',()=>{let src=null,out={width:0,height:0,getContext(){return {fillRect(){},drawImage(...args){src=args},set fillStyle(v){},set imageSmoothingEnabled(v){},set imageSmoothingQuality(v){}}}};R.crop({width:675,height:250},A[0],()=>out);assert.equal(src[1],A[0].left);assert.equal(src[2],A[0].top);assert.ok(out.width>=A[0].width)});
t('valid merchant result good',()=>assert.equal(R.isGoodCandidate({name:'Roborock S9',autoFillPrice:1190000}),true));
t('no product unknown',()=>assert.equal(R.isGoodCandidate({name:'',autoFillPrice:1190000}),false));
t('no-price blocked',()=>assert.equal(R.isGoodCandidate({name:'Roborock',autoFillPrice:null}),false));
t('Roborock discounted OCR text extracts 1,190,000',()=>assert.equal(S.analyze('로보락 로봇청소기 S9 MaxV Ultra\n최저가 35% 1,190,000원').autoFillPrice,1190000));
t('Roborock old + discounted from two passes',()=>{const x=S.combine(['로보락 S9 MaxV Ultra\n1,840,000원','최저가 35%1,190,000원']);assert.equal(x.autoFillPrice,1190000);assert.equal(x.originalPrice,1840000)});
t('two prices on one row remain ambiguous',()=>assert.equal(S.analyze('로보락\n20% 1,000,000원 800,000원').autoFillPrice,null));
t('reward price never automatically applied',()=>assert.equal(S.analyze('로보락\n적립 13,160원').autoFillPrice,null));
t('Tesseract full frame still retained',()=>assert.match(app,/recognize\(image,'1차 전체 화면'/));
t('per-region progressive OCR',()=>assert.match(app,/PriceHunterOCRRegions\.crop\(image,area\)/));
t('price region always checked',()=>assert.match(app,/index>0&&sufficient\(\)/));
t('text region can use PSM 11',()=>assert.equal(A[1].psm,11));
t('merchant regression safety still active',()=>assert.match(html,/<script src="merchantguard\.js"><\/script><script src="ocr-regions\.js"><\/script>/));
t('PWA caches OCR regions module',()=>assert.match(sw,/ocr-regions\.js/));
t('new cache invalidates previous version',()=>assert.match(sw,/price-hunter-v070/));
let fail=0;for(const [label,fn] of tests){try{fn();console.log('PASS',label)}catch(err){fail++;console.error('FAIL',label,err.message)}}
console.log(`Region OCR ${tests.length-fail}/${tests.length}`);if(fail)process.exitCode=1;
