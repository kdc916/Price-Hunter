const assert=require('node:assert/strict');
const fs=require('node:fs');
const S=require('../screenshot.js');
require('../catalogguard.js');
require('../checkoutguard.js');
const app=fs.readFileSync(require('node:path').join(__dirname,'..','app.js'),'utf8');
const cases=[];const t=(name,fn)=>cases.push([name,fn]);
const samsung='삼성전자 DDR5-5600 (16GB)\n최저가 349,690원\n멤버십/카드결제 최대 혜택가\n무통장입금시 344,840원\nN+멤버십 최대 13,160원 적립 시\n네이버페이 1만원 지급';
const low='삼성전자 DDR5-5600 (16GB)\n344,840원\n회원 혜택가';
const focused='최저가\n349,690원\n무통장입금시 344,840원';
t('primary price',()=>assert.equal(S.analyze(samsung).price,349690));
t('trusted price confidence',()=>assert.equal(S.analyze(samsung).priceConfidence,'high'));
t('benefit price separate',()=>assert.deepEqual(S.analyze(samsung).conditionalPrices,[344840]));
t('reward excluded',()=>assert.ok(S.analyze(samsung).prices.some(x=>x.value===13160&&x.type==='excluded')));
t('multi-pass recovers selling price',()=>assert.equal(S.combine([low,focused]).price,349690));
t('multi-pass trusted price',()=>assert.equal(S.combine([low,focused]).priceConfidence,'high'));
t('orphan benefit is not selling price',()=>assert.equal(S.combine([low,'무통장입금시 344,840원']).price,null));
t('orphan benefit recognized',()=>assert.ok(S.combine([low,'무통장입금시 344,840원']).conditionalPrices.includes(344840)));
t('focused region works without product name',()=>assert.equal(S.analyze(focused).price,349690));
t('conflicting true selling prices not automatic',()=>assert.equal(S.combine(['판매가 999,000원','판매가 899,000원']).price,null));
t('Sony A7V regression',()=>assert.equal(S.analyze('소니 A7V ILCE-7M5\n3,533,050원\n11% 3,109,090원\n68,181원 적립').price,3109090));
t('dedicated price crop',()=>assert.match(app,/function focusPriceOCR\(source\)/));
t('fourth OCR pass',()=>assert.match(app,/recognize\(focusPriceOCR\(image\)/));
t('auto apply uses evidence policy instead of high-only gate',()=>assert.match(app,/PriceHunterCheckoutGuard\?\.autoPurchase\(result\)/));
t('conditional values rejected from manual options',()=>assert.match(app,/type==='conditional'\|\|x\.type==='excluded'/));
t('explicit confirm before manual assignment',()=>assert.ok(app.includes('if(!confirm(')));
t('manual assignment updates quick calculation',()=>assert.match(app,/\$\('purchasePrice'\)\.value=String\(candidate\);renderQuick\(\)/));
t('optimized OCR stopping rule',()=>assert.match(app,/PriceHunterCheckoutGuard\?\.autoPurchase\(merged\)/));
let bad=0;for(const [name,fn] of cases){try{fn();console.log('PASS',name)}catch(e){bad++;console.error('FAIL',name,e.message)}}
console.log((cases.length-bad)+'/'+cases.length+' checkout OCR regression');if(bad)process.exitCode=1;
